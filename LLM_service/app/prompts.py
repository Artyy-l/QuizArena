def _distribution(request: GenerationRequest) -> dict[QuestionType, int]:
    counts = Counter(request.question_types)
    weighted_types = list(counts.items())
    total_weight = sum(count for _, count in weighted_types)

    result: dict[QuestionType, int] = {
        question_type: request.number * weight // total_weight
        for question_type, weight in weighted_types
    }

    assigned = sum(result.values())
    remainder = request.number - assigned
    for index in range(remainder):
        question_type, _ = weighted_types[index % len(weighted_types)]
        result[question_type] += 1

    return result


def _has_meaningful_text(value: str | None) -> bool:
    return any(char.isalnum() for char in (value or ""))


def _topic_hint(request: GenerationRequest) -> str:
    topic = (request.topic or "").strip()
    return topic if _has_meaningful_text(topic) else DEFAULT_TOPIC


def build_user_prompt(request: GenerationRequest) -> str:
    distribution = _distribution(request)
    topic = _topic_hint(request)
    has_material = request.has_material
    type_rules = "\n".join(
        f"- {question_type.value}: {QUESTION_TYPE_RULES[question_type]} (количество: {count})"
        for question_type, count in distribution.items()
    )

    source_rule = (
        "Ниже передан текст, извлечённый из файлов. Считай его главным источником фактов; "
        "уточнение пользователя задаёт только фокус внутри материала. "
        "Если текста мало, укажи ограничение в warnings."
        if has_material else
        "Извлечённый материал не передан. Сгенерируй предметный учебный квиз по указанной теме."
    )

    parts = [
        f"Тема/уточнение и извлечённый материал:\n{topic}",
        f"Количество вопросов: {request.number}",
        "Язык вопросов: русский.",
        source_rule,
        "Не создавай вопросы про генерацию квиза, промпты или инструкции.",
        "Каждый вопрос должен проверять понимание учебной темы.",
        "Сгенерируй вопросы следующих типов:",
        type_rules,
        "Строго генерируй только перечисленные выше типы. Если указан один тип, все вопросы должны быть именно этого типа. Не заменяй 100k1 на single_choice, multiple_choice или true_false.",
        "Для типов multiple_choice и 100k1 строго соблюдай специальные требования к составу правильных и неправильных ответов.",
        "Поле question должно содержать только сам вопрос: без инструкций о количестве правильных ответов или вариантов.",
        "В explanation не ссылайся на служебные id или порядок вариантов: пользователь не видит буквенные id, а порядок может перемешиваться. Называй ответы по смыслу или цитируй их текст.",
        "Порядок вариантов не должен систематически выдавать правильный ответ; correct_answers определяй по id, а не по позиции в списке.",
        "Если нужны математические формулы, используй LaTeX-разметку: \\(...\\) для формул в строке и \\[...\\] для отдельных формул. Не оставляй формулы без разделителей: пиши \\(A=B\\), \\(a_{ij}=b_{ij}\\), а не A=B, a_{ij}=b_{ij}.",
    ]

    parts.append(
        """
Верни JSON строго в формате:
{
  "topic": "...",
  "language": "ru",
  "question_count": 0,
  "questions": [
    {
      "id": "q1",
      "type": "single_choice | multiple_choice | true_false | 100k1",
      "difficulty": "easy | medium | hard",
      "question": "...",
      "options": [
        {"id": "A", "text": "...", "nominal": null}
      ],
      "correct_answers": ["A"],
      "explanation": "...",
      "source_reference": "...",
      "metadata": {}
    }
  ],
  "warnings": []
}

Дополнительные требования:
- question_count должен совпадать с реальным числом вопросов.
- id вопросов должны быть уникальными.
- id вариантов внутри одного вопроса должны быть уникальными.
- Не добавляй markdown, комментарии или пояснительный текст вокруг JSON.
- Значение поля type у каждого вопроса должно быть только из перечисленных в запросе типов.
- Если запрошен только 100k1, у каждого вопроса type должен быть "100k1".
- Для 100k1 заполни nominal у каждого варианта по оценённой популярности; для остальных типов используй null.
- Для 100k1 metadata оставь пустым объектом, если нет действительно необходимых служебных данных.
- Не создавай вопросы типов ordering, matching и short_answer.
- Поле explanation обязательно для каждого вопроса и не должно быть пустым.
- В explanation не ссылайся на буквенные id вариантов (A, B, C и т. д.) или их порядок ("первый", "второй" и т. п.). Используй только текст ответа или смысловое описание.
- Математические формулы в question, options.text и explanation всегда записывай внутри LaTeX-разделителей \\(...\\) или \\[...\\].
""".strip()
    )

    return "\n\n".join(parts)
